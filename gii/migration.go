package gii

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"time"

	frameworkdb "github.com/chitushka/framework/db"
	"github.com/chitushka/framework/db/ar"
	"github.com/chitushka/framework/db/migration"
)

var sqlTypePattern = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*(?:\s+[A-Za-z][A-Za-z0-9_]*)*(?:\([0-9, ]+\))?$`)

func GenerateMigrationSQL(schema ar.TableSchema, dialect frameworkdb.Dialect) (string, string, error) {
	if dialect == nil {
		return "", "", errors.New("gii: dialect is required")
	}
	if len(schema.Columns) == 0 {
		return "", "", errors.New("gii: schema has no columns")
	}
	parts := strings.Split(schema.Name, ".")
	quoted := make([]string, len(parts))
	for index, part := range parts {
		if !identifier.MatchString(part) {
			return "", "", fmt.Errorf("gii: invalid table %q", schema.Name)
		}
		quoted[index] = dialect.QuoteIdentifier(part)
	}
	table := strings.Join(quoted, ".")
	definitions := make([]string, 0, len(schema.Columns)+1)
	primary := make([]string, 0)
	for _, column := range schema.Columns {
		if !identifier.MatchString(column.Name) {
			return "", "", fmt.Errorf("gii: invalid column %q", column.Name)
		}
		dataType := strings.TrimSpace(column.DataType)
		if dataType == "" {
			dataType = sqlTypeForGo(column.GoType, dialect.Name())
		}
		if !sqlTypePattern.MatchString(dataType) {
			return "", "", fmt.Errorf("gii: unsafe SQL type %q", dataType)
		}
		definition := dialect.QuoteIdentifier(column.Name) + " " + strings.ToUpper(dataType)
		if column.AutoIncrement {
			switch dialect.Name() {
			case frameworkdb.PostgreSQL:
				if strings.Contains(strings.ToUpper(dataType), "BIG") {
					definition = dialect.QuoteIdentifier(column.Name) + " BIGSERIAL"
				} else {
					definition = dialect.QuoteIdentifier(column.Name) + " SERIAL"
				}
			case frameworkdb.MySQL:
				definition += " AUTO_INCREMENT"
			case frameworkdb.SQLServer:
				definition += " IDENTITY(1,1)"
			case frameworkdb.Oracle:
				definition += " GENERATED BY DEFAULT AS IDENTITY"
			}
		}
		if !column.Nullable {
			definition += " NOT NULL"
		}
		definitions = append(definitions, definition)
		if column.PrimaryKey {
			primary = append(primary, dialect.QuoteIdentifier(column.Name))
		}
	}
	if len(primary) > 0 {
		definitions = append(definitions, "PRIMARY KEY ("+strings.Join(primary, ", ")+")")
	}
	return "CREATE TABLE " + table + " (\n    " + strings.Join(definitions, ",\n    ") + "\n);\n", "DROP TABLE " + table + ";\n", nil
}

func WriteMigration(directory, name string, now time.Time, schema ar.TableSchema, dialect frameworkdb.Dialect) (migration.Files, error) {
	up, down, err := GenerateMigrationSQL(schema, dialect)
	if err != nil {
		return migration.Files{}, err
	}
	return migration.CreateSQL(directory, name, now, up, down)
}

func sqlTypeForGo(value, dialect string) string {
	value = strings.TrimPrefix(value, "*")
	switch value {
	case "bool":
		return "BOOLEAN"
	case "int", "int32", "int64", "uint", "uint32", "uint64":
		return "BIGINT"
	case "float32", "float64":
		return "DOUBLE PRECISION"
	case "time.Time":
		return "TIMESTAMP"
	case "[]byte":
		if dialect == frameworkdb.PostgreSQL {
			return "BYTEA"
		}
		return "BLOB"
	default:
		return "VARCHAR(255)"
	}
}
