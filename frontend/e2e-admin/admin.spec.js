import { test, expect } from "@playwright/test"

async function login(page, username, password) {
  await page.goto("/login")
  await page.getByLabel("Имя пользователя", { exact: true }).fill(username)
  await page.getByLabel("Пароль", { exact: true }).fill(password)
  await page.getByRole("button", { name: "Войти", exact: true }).click()
  await expect(page).toHaveURL(/\/admin$/)
}
async function csrf(page) { return page.locator('input[name="_csrf"]').first().inputValue() }
async function post(page, path, form) { return page.request.post(path, { form: { _csrf: await csrf(page), ...form }, maxRedirects: 0 }) }
async function createRole(page, name, values) {
  await page.goto("/admin/roles/new")
  await page.getByLabel("Название роли").fill(name)
  await page.getByLabel("Описание", { exact: true }).fill(`Role ${name}`)
  for (const permission of values) await page.getByLabel(permission, { exact: true }).check()
  await page.getByRole("button", { name: "Сохранить", exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/roles$/)
}
async function createUser(page, name) {
  await page.goto("/admin/users/new")
  await page.getByLabel("Имя пользователя", { exact: true }).fill(name)
  await page.getByLabel("Отображаемое имя").fill(`User ${name}`)
  await page.getByLabel("Пароль", { exact: true }).fill("reviewer-e2e-password")
  await page.getByRole("button", { name: "Сохранить", exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/users$/)
}
async function assign(page, name, role) {
  await page.goto("/admin/assignments")
  const card = page.locator("section.card").filter({ has: page.getByRole("heading", { name, exact: true }) })
  await card.getByLabel("Добавить роль").selectOption(role)
  await card.getByRole("button", { name: "Назначить", exact: true }).click()
  await expect(card.getByText(role, { exact: true }).first()).toBeVisible()
}

test("guest cannot enter administrative pages or submit mutations", async ({ page }) => {
  for (const path of ["/admin", "/admin/catalog", "/admin/users", "/admin/roles", "/admin/assignments", "/admin/audit"]) {
    await page.goto(path); await expect(page).toHaveURL(/\/login$/)
  }
  const denied = await page.request.post("/admin/users/new", { form: { username: "admin", role: "administrator" } })
  expect(denied.status()).toBe(403)
  await page.getByLabel("Имя пользователя", { exact: true }).fill("admin")
  await page.getByLabel("Пароль", { exact: true }).fill("wrong-password")
  await page.getByRole("button", { name: "Войти", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Неверное имя пользователя или пароль")
})

test("editor has catalog CRUD but cannot escalate through UI or direct HTTP", async ({ page }) => {
  await login(page, "editor", "editor-e2e-password")
  await expect(page.getByRole("link", { name: "Пользователи", exact: true })).toHaveCount(0)
  await expect(page.getByRole("link", { name: "Роли", exact: true })).toHaveCount(0)
  await page.goto("/admin/catalog/new")
  await page.getByRole("button", { name: "Сохранить", exact: true }).click()
  await expect(page.getByRole("alert")).toBeVisible()
  await page.getByLabel("Код", { exact: true }).fill("browser-editor")
  await page.getByLabel("Название", { exact: true }).fill("Editor created")
  await page.getByRole("button", { name: "Сохранить", exact: true }).click()
  let row = page.getByRole("row").filter({ hasText: "browser-editor" })
  await row.getByRole("link", { name: "Изменить", exact: true }).click()
  await page.getByLabel("Название", { exact: true }).fill("Editor updated")
  await page.getByRole("button", { name: "Сохранить", exact: true }).click()
  row = page.getByRole("row").filter({ hasText: "browser-editor" })
  await expect(row).toContainText("Editor updated")
  await page.screenshot({ path: "test-results/admin-editor.png", fullPage: true })
  expect((await post(page, "/admin/users/new", { username: "attacker", password: "attacker-password", display_name: "Attacker", active: "1", version: "1", role: "administrator" })).status()).toBe(403)
  expect((await post(page, "/admin/roles/new", { name: "escalated", description: "Bad", permissions: "users.manage", version: "1" })).status()).toBe(403)
  expect((await post(page, "/admin/assignments/add", { user_id: "editor", role: "administrator", version: "1" })).status()).toBe(403)
  expect((await post(page, "/admin/catalog/new", { code: "injected", name: "Injected", version: "1", is_admin: "true" })).status()).toBe(400)
  for (const path of ["/admin/users", "/admin/roles", "/admin/assignments", "/admin/audit"]) expect((await page.request.get(path)).status()).toBe(403)
  await row.getByRole("button", { name: "Удалить", exact: true }).click()
  await expect(page.getByRole("row").filter({ hasText: "browser-editor" })).toHaveCount(0)
})

test("admin manages users/roles/assignments, audits changes and retains data after restart", async ({ page, browser, request }) => {
  await login(page, "admin", "admin-e2e-password")
  await createRole(page, "auditor", ["catalog.view", "audit.view"])
  await createUser(page, "reviewer")
  await assign(page, "reviewer", "auditor")
  const reviewerContext = await browser.newContext({ baseURL: "http://127.0.0.1:8281" })
  const reviewer = await reviewerContext.newPage()
  try {
    await login(reviewer, "reviewer", "reviewer-e2e-password")
    await reviewer.goto("/admin/catalog")
    await expect(reviewer.getByRole("link", { name: "Создать запись" })).toHaveCount(0)
    await reviewer.goto("/admin/audit")
    await expect(reviewer.getByRole("row").filter({ hasText: "assignment.add" }).first()).toBeVisible()
    await page.goto("/admin/users")
    let userRow = page.getByRole("row").filter({ hasText: "reviewer" })
    await userRow.getByRole("link", { name: "Изменить", exact: true }).click()
    await page.getByLabel("Отображаемое имя").fill("Reviewer persisted")
    await page.getByRole("button", { name: "Сохранить", exact: true }).click()
    await page.goto("/admin/roles/auditor/edit")
    await page.getByLabel("Описание", { exact: true }).fill("Auditor persisted")
    await page.getByLabel("catalog.view", { exact: true }).uncheck()
    await page.getByRole("button", { name: "Сохранить", exact: true }).click()
    expect((await reviewer.request.get("/admin/catalog")).status()).toBe(403)
    await page.goto("/admin/catalog/new")
    await page.getByLabel("Код", { exact: true }).fill("restart-proof")
    await page.getByLabel("Название", { exact: true }).fill("Persisted after restart")
    await page.getByRole("button", { name: "Сохранить", exact: true }).click()
    await page.screenshot({ path: "test-results/admin-catalog.png", fullPage: true })
    await page.goto("/admin/assignments")
    await page.screenshot({ path: "test-results/admin-assignments.png", fullPage: true })
    // Actual OS process restart, with the same PostgreSQL database and no seed replay.
    expect((await request.post("http://127.0.0.1:8289/restart")).status()).toBe(204)
    await page.goto("/admin/catalog"); await expect(page).toHaveURL(/\/login$/)
    await login(page, "admin", "admin-e2e-password")
    await page.goto("/admin/catalog"); await expect(page.getByText("Persisted after restart", { exact: true })).toBeVisible()
    await page.goto("/admin/users"); await expect(page.getByText("Reviewer persisted", { exact: true })).toBeVisible()
    await page.goto("/admin/roles"); await expect(page.getByText("Auditor persisted", { exact: true })).toBeVisible()
    await page.goto("/admin/assignments")
    const card = page.locator("section.card").filter({ has: page.getByRole("heading", { name: "reviewer", exact: true }) })
    await expect(card.locator(".role-chip")).toContainText("auditor")
    await card.getByRole("button", { name: "Отозвать auditor", exact: true }).click()
    await expect(card.locator(".role-chip")).toHaveCount(0)
    await page.goto("/admin/audit"); await expect(page.getByRole("row").filter({ hasText: "assignment.revoke" }).first()).toBeVisible()
    await page.screenshot({ path: "test-results/admin-audit.png", fullPage: true })
    await page.goto("/admin/users")
    userRow = page.getByRole("row").filter({ hasText: "reviewer" })
    await userRow.getByRole("button", { name: "Удалить", exact: true }).click()
    await expect(page.getByRole("row").filter({ hasText: "reviewer" })).toHaveCount(0)
    await page.goto("/admin/roles")
    await page.getByRole("row").filter({ hasText: "auditor" }).getByRole("button", { name: "Удалить", exact: true }).click()
    await expect(page.getByRole("row").filter({ hasText: "auditor" })).toHaveCount(0)
    await page.goto("/admin/users")
    const adminRow = page.getByRole("row").filter({ hasText: "admin" })
    const adminID = await adminRow.getAttribute("data-user-id"), version = await adminRow.getAttribute("data-version")
    expect((await post(page, `/admin/users/${adminID}/delete`, { version })).status()).toBe(409)
  } finally { await reviewerContext.close() }
})

test("delegated RBAC manager cannot grant itself permissions it does not hold", async ({ page, browser }) => {
  await login(page, "admin", "admin-e2e-password")
  await createRole(page, "delegate", ["rbac.manage"])
  await createUser(page, "delegate")
  await assign(page, "delegate", "delegate")
  const context = await browser.newContext({ baseURL: "http://127.0.0.1:8281" })
  const delegated = await context.newPage()
  try {
    await login(delegated, "delegate", "reviewer-e2e-password")
    await delegated.goto("/admin/roles/delegate/edit")
    await expect(delegated.getByLabel("users.manage", { exact: true })).toBeDisabled()
    const version = await delegated.locator('input[name="version"]').inputValue()
    expect((await post(delegated, "/admin/roles/delegate/edit", { name: "delegate", description: "Escalated", permissions: "users.manage", version })).status()).toBe(403)
    await delegated.goto("/admin/assignments")
    const card = delegated.locator("section.card").filter({ has: delegated.getByRole("heading", { name: "delegate", exact: true }) })
    await expect(card.getByRole("option", { name: "administrator", exact: true })).toHaveCount(0)
    const user_id = await card.getAttribute("data-user-id"), currentVersion = await card.getAttribute("data-version")
    expect((await post(delegated, "/admin/assignments/add", { user_id, role: "administrator", version: currentVersion })).status()).toBe(403)
    expect((await delegated.request.get("/admin/users")).status()).toBe(403)
  } finally { await context.close() }
})
